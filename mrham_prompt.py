"""
=============================================================
 mrham_prompt.py — Layer 3 AI 프롬프트 빌더
=============================================================
 핵심 변경: AI 역할이 '발굴'에서 '해석'으로 바뀐다.

 [변경 전] "60개 리스트에서 좋은 걸 골라줘"
   → 유명 종목 편향, 환각, 근거 없는 확신
 [변경 후] "정량 상위 15개다. 함정을 걸러내고 2개만 골라라"
   → LLM이 잘하는 일(맥락 해석·함정 탐지)만 수행
=============================================================
"""

from __future__ import annotations

import datetime

KST = datetime.timezone(datetime.timedelta(hours=9))


def today_kst_str() -> str:
    return datetime.datetime.now(KST).strftime("%Y년 %m월 %d일")


# ═══════════════════════════════════════════════════════════
#  Layer 3 — 신규 추천 프롬프트 (해석 전용)
# ═══════════════════════════════════════════════════════════
def build_recommendation_prompt(candidate_ctx: str,
                                market_ctx: str,
                                disclosure_ctx: str,
                                portfolio_ctx: str,
                                performance_ctx: str = "",
                                today: str = "",
                                n_pick: int = 2) -> str:
    """
    스크리닝 후보를 '해석'하는 프롬프트.
    ※ 순수 함수 — 네트워크 없이 테스트 가능
    """
    d = today or today_kst_str()
    perf_block = f"""
[이 시스템의 과거 추천 성과 — 겸손의 근거]
{performance_ctx}
※ 과거 성과가 저조하다면 그 사실을 인정하고 더 보수적으로 판단할 것.
""" if performance_ctx else ""

    return f"""오늘은 {d}입니다.

당신의 역할은 **종목 발굴이 아니라 정량 스크리닝 결과의 해석**입니다.
아래 후보는 전체 상장종목(약 2,700개)에서 하드컷 필터와 4팩터 랭킹을
통과한 상위 종목입니다. 당신이 새로 종목을 떠올릴 필요가 없습니다.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[정량 스크리닝 상위 후보]
{candidate_ctx}

[시장 환경]
{market_ctx}

[DART 공시]
{disclosure_ctx}

[내 보유 포트폴리오 — 중복 추천 금지용]
{portfolio_ctx}
{perf_block}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🚨 [필수 사고 절차]

1단계 — 함정 탐지 (가장 중요)
  정량 점수가 높다고 좋은 종목이 아닙니다. 아래를 반드시 검증하세요.
  ⛔ 가치 함정: PER·PBR이 낮은 이유가 '싸서'가 아니라 '구조적 쇠퇴'인가?
  ⛔ 일회성 이익: ROE가 자산매각·환입 등 일회성 이익 때문인가?
  ⛔ 모멘텀 과열: 이미 급등해 되돌림 위험이 큰 구간인가?
  ⛔ 공시 리스크: 위 DART 목록에 해당 종목의 악재 공시가 있는가?
  ⛔ 뉴스 리스크: 시장 환경상 해당 섹터가 역풍을 맞고 있는가?
  → 함정으로 판단한 종목은 반드시 '탈락 사유'와 함께 명시하세요.

2단계 — 최종 선별
  함정을 걸러낸 뒤 상위 {n_pick}개만 추천합니다.
  ⛔ 이미 보유 중인 종목은 추천 금지.
  ⛔ 후보 목록에 없는 종목은 절대 추천 금지 (시세 데이터가 없어 검증 불가).
  ⛔ 목표가·손절가는 반드시 후보 목록의 '현재가' 기준으로 계산.

3단계 — 불확실성 명시
  확신할 수 없는 부분은 '확인 필요'로 표기하세요.
  데이터가 없으면 N/A. 추정·상상 금지.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
📝 [출력 형식 — 반드시 준수]

## 💎 신규 추천

### 🔻 함정 판정 — 탈락 종목
- **종목명(코드)**: 탈락 사유 1줄
(최소 2개 이상 — 상위 후보를 전부 통과시키지 말 것)

### ✅ 최종 추천 ({n_pick}종목)

#### 📌 종목명(종목코드)
- **정량 근거**: 종합점수 OO점 / 가치 OO · 퀄리티 OO · 모멘텀 OO · 수급 OO
- **정성 근거**: 왜 이 점수가 함정이 아닌지 2~3줄 (뉴스·공시 연계)
- **현재가 / 목표가 / 손절가**: OO원 / OO원(+OO%) / OO원(-OO%)
- **투자 기간**: 단기(3개월내) / 중기(3~12개월) / 장기(1년+)
- **최대 리스크**: 이 판단이 틀릴 수 있는 가장 큰 이유 1줄

### ⚠️ 이번 추천의 신뢰도
- **확신 수준**: 상 / 중 / 하 — 그리고 그 이유 1줄
"""


# ═══════════════════════════════════════════════════════════
#  긴급 공시 경고 (AI 호출 없이 즉시 표시)
# ═══════════════════════════════════════════════════════════
def build_critical_alert_text(alerts: list) -> str:
    """
    보유 종목 강한 악재 공시를 즉시 경고 텍스트로.
    AI를 거치지 않으므로 지연·환각 없음.
    ※ 순수 함수
    """
    if not alerts:
        return ""
    lines = ["🚨 **보유 종목 긴급 공시 — 즉시 확인 필요**", ""]
    for a in alerts:
        lines.append(f"- **{a['corp_name']}({a['code']})** — {a['report_nm']}")
        lines.append(f"  · {a['reason']} · 접수일 {a['rcept_dt']}")
        lines.append(f"  · [공시 원문 보기]({a['url']})")
    lines.append("")
    lines.append("※ 이 경고는 AI 분석을 거치지 않은 DART 원문 기반입니다. 원문을 직접 확인하세요.")
    return "\n".join(lines)
